"""Build the loading page's Ark Pixel subset from the pinned local BDF cache."""
from pathlib import Path
import hashlib
import json
import re
import tempfile
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/fonts/loading"
OUT.mkdir(parents=True, exist_ok=True)
subset = OUT / "pasture-loading-12.bdf"
cached = Path(tempfile.gettempdir()) / "sheep-run-ui-font-sources/2026.09.25/full-ark-pixel-12px-monospaced-zh_hans.bdf"
source = cached if cached.exists() else subset
text = source.read_text(encoding="utf-8")
tips = (ROOT / "src/data/loadingTips.ts").read_text(encoding="utf-8").split("LOADING_TIPS = [", 1)[1].split("] as const", 1)[0]
stages = (ROOT / "src/ui/LoadingProgress.ts").read_text(encoding="utf-8").split("LOADING_STAGE_LABELS = {", 1)[1].split("} as const", 1)[0]
copy = "小贴士0123456789%…" + "".join(re.findall(r'"([^\"]+)"', tips + stages))
chars = set(copy)
ascent = int(re.search(r"FONT_ASCENT (\d+)", text)[1])
glyphs, blocks = {}, []
for block in text.split("STARTCHAR ")[1:]:
    code = int(re.search(r"ENCODING (-?\d+)", block)[1])
    if code < 0 or chr(code) not in chars:
        continue
    width, height, ox, oy = map(int, re.search(r"BBX ([^\n]+)", block)[1].split())
    advance = int(re.search(r"DWIDTH (\d+)", block)[1])
    rows = block.split("BITMAP\n")[1].split("ENDCHAR")[0].strip().splitlines()
    glyphs[code] = (width, height, ox, ascent - height - oy, advance, rows)
    blocks.append("STARTCHAR " + block.split("ENDCHAR", 1)[0] + "ENDCHAR\n")
missing = chars - set(map(chr, glyphs))
if missing:
    raise RuntimeError("Pinned local BDF missing: " + "".join(sorted(missing)))
atlas = Image.new("RGBA", (16 * 14, ((len(glyphs) + 15) // 16) * 14))
metrics = {}
for index, (code, (width, height, ox, oy, advance, rows)) in enumerate(sorted(glyphs.items())):
    x, y = index % 16 * 14 + 1, index // 16 * 14 + 1
    for row, bits in enumerate(rows):
        for column in range(width):
            if int(bits, 16) & (1 << (len(bits) * 4 - 1 - column)):
                atlas.putpixel((x + column, y + row), (255, 255, 255, 255))
    metrics[code] = dict(x=x, y=y, width=width, height=height, xoffset=ox, yoffset=oy, advance=advance)
atlas.save(OUT / "pasture-loading-12.png", optimize=True)
header = text.split("CHARS ", 1)[0]
subset.write_text(header + f"CHARS {len(blocks)}\n" + "".join(blocks) + "ENDFONT\n", encoding="utf-8")
module = 'export const LOADING_PIXEL_FONT_URL = new URL("../../assets/fonts/loading/pasture-loading-12.png", import.meta.url).href;\n'
module += 'export interface LoadingGlyph { x: number; y: number; width: number; height: number; xoffset: number; yoffset: number; advance: number; }\n'
module += 'export const LOADING_PIXEL_GLYPHS: Readonly<Record<number, LoadingGlyph>> = ' + json.dumps(metrics, ensure_ascii=False, separators=(",", ":")) + ';\n'
(ROOT / "src/data/loadingPixelFont.ts").write_text("// Generated by tools/build-loading-font.py; Ark Pixel 12, OFL 1.1.\n" + module, encoding="utf-8")
(OUT / "OFL.txt").write_bytes((ROOT / "assets/fonts/ark-OFL.txt").read_bytes())
(OUT / "source.json").write_text(json.dumps(dict(family="Pasture Loading Pixel", upstream="Ark Pixel Font", version="2026.09.25", size=12, license="SIL OFL 1.1", subsetGlyphs=len(metrics), sourceBdfSha256=hashlib.sha256(subset.read_bytes()).hexdigest(), atlasSha256=hashlib.sha256((OUT / "pasture-loading-12.png").read_bytes()).hexdigest(), construction="Exact BDF bits, no font rasterization or smoothing", source="https://github.com/TakWolf/ark-pixel-font/releases/tag/2026.09.25"), indent=2) + "\n", encoding="utf-8")
print(f"Loading Ark Pixel: {len(metrics)} glyphs, {atlas.size}, all tips covered")
