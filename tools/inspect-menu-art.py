"""Read alpha bounds and digit frames; generated PNG files stay untouched."""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "assets/ui/menu-reference-v2"
records = {}
for name in ("title", "start", "wardrobe", "settings", "score", "digits"):
    path = DIRECTORY / f"{name}-v2.png"
    image = Image.open(path).convert("RGBA")
    alpha = image.getchannel("A")
    bounds = alpha.getbbox()
    assert bounds and alpha.getextrema() == (0, 255), f"{name}: transparent alpha required"
    solid = alpha.point(lambda value: 255 if value >= 128 else 0)
    x, y, right, bottom = solid.getbbox()
    x, y, right, bottom = max(0, x-4), max(0, y-4), min(image.width, right+4), min(image.height, bottom+4)
    record = {"width": image.width, "height": image.height, "alphaBounds": list(bounds), "ink": {"x": x, "y": y, "width": right-x, "height": bottom-y}, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    if name == "digits":
        # Fully transparent gutters delimit the ten generated numeral frames.
        occupied = [solid.crop((column, 0, column+1, image.height)).getbbox() is not None for column in range(image.width)]
        runs, start = [], None
        for column, filled in enumerate(occupied + [False]):
            if filled and start is None:
                start = column
            elif not filled and start is not None:
                runs.append((start, column)); start = None
        assert len(runs) == 10, f"Expected ten separated digit frames, got {runs}"
        record["glyphs"] = {}
        for digit, (left, right) in enumerate(runs):
            top, bottom = solid.crop((left, 0, right, image.height)).getbbox()[1::2]
            # Keep original RGBA edge pixels around the measured solid glyph.
            record["glyphs"][str(digit)] = {"x": left-4, "y": top-4, "width": right-left+8, "height": bottom-top+8}
    records[name] = record

# Measure solid artwork with a four-pixel edge guard. PNG pixels remain unchanged.
(DIRECTORY / "geometry.json").write_text(json.dumps(records, indent=2) + "\n", encoding="utf-8")
(ROOT / "src/data/menuArtGeometry.ts").write_text("// Generated by tools/inspect-menu-art.py. Source PNG pixels are unchanged.\nexport const MENU_ART_GEOMETRY = " + json.dumps(records, indent=2) + " as const;\n", encoding="utf-8")
print(json.dumps(records, indent=2))
